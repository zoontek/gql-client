import type { TypedDocumentNode } from "@graphql-typed-document-node/core";

import {
  ClientCache,
  type ConnectionUpdateConfig,
  type EdgeList,
} from "../cache/cache";
import type { SerializedCache } from "../cache/serialize";
import type { SchemaConfig } from "../cache/types";
import { entriesOverlap, type WatchedEntriesBox } from "../cache/watch";
import { getOperationName } from "../graphql/ast";
import { printDocument } from "../graphql/print";
import { transformDocument } from "../graphql/transform";
import type { AnyVariables, Connection, JsonArray, JsonValue } from "../types";
import {
  deleteIfUnchanged,
  getOrInsert,
  identity,
  isRecord,
  stableStringify,
} from "../utils";
import { ClientError } from "./errors";

const serializedVariablesCache = new WeakMap<AnyVariables, string>();

export const serializeVariables = (variables: AnyVariables): string =>
  getOrInsert(serializedVariablesCache, variables, stableStringify);

/**
 * Options of the `Client` constructor.
 *
 * @see https://zoontek.github.io/gql-client/client
 */
export type ClientConfig = {
  /** GraphQL endpoint. The client sends each request here as an HTTP `POST`. */
  url: string;
  /** Interface and union map generated by `gql-schema-config`. */
  schemaConfig: SchemaConfig;
  /**
   * Request timeout in milliseconds. Set `Infinity` to disable it.
   *
   * @defaultValue 10_000
   */
  timeout?: number;
  /**
   * Returns the request to send in place of the one the client built.
   * Read the body from `request.clone()`, never from `request`.
   *
   * @see https://zoontek.github.io/gql-client/request-transforms
   */
  transformRequest?: (request: Request) => Request | Promise<Request>;
};

// One per document and serialized variables. Shared while in flight. Kept after
// success only while the cache cannot read the response, and after rejection
// only until a `suspense` call gets it (see KEEP_REJECTED_MS).
type StoredRequest = {
  promise: Promise<unknown>;
  settled: boolean;
  rejectedAt: number | undefined;
  // A `suspense` call got this promise before it settled.
  suspense: boolean;
};

// React renders a suspended component again a few ms after its promise rejects.
// After this delay the component is gone, and the next call must not get the
// rejection.
const KEEP_REJECTED_MS = 1000;

type ActiveQuery = {
  // oxlint-disable-next-line typescript/no-explicit-any
  document: TypedDocumentNode<any, any>;
  variables: AnyVariables;
};

type ConnectionUpdate<Node> = [Connection<Node>, ConnectionUpdateConfig<Node>];

type AddEdges = <A>(
  connection: Connection<A>,
  edges: EdgeList<A>,
) => ConnectionUpdate<A>;

type RemoveEdges = <A>(
  connection: Connection<A>,
  ids: (string | number)[],
) => ConnectionUpdate<A>;

const prepend: AddEdges = (connection, edges) => [
  connection,
  { prepend: edges },
];

const append: AddEdges = (connection, edges) => [connection, { append: edges }];

const remove: RemoveEdges = (connection, ids) => [connection, { remove: ids }];

// The spec forbids an empty `errors` array, but some servers send one with
// valid `data`.
const getGraphQLErrors = (
  json: Record<PropertyKey, unknown>,
): JsonArray | undefined =>
  Array.isArray(json.errors) && json.errors.length > 0
    ? json.errors
    : undefined;

/**
 * Called after a mutation with its `data` and `variables`.
 * Returns the change to apply to a cached connection, made with `prepend`,
 * `append` or `remove`, or `undefined` to keep the connection as it is.
 *
 * @see https://zoontek.github.io/gql-client/mutations#updating-connections
 */
export type GetConnectionUpdate<
  Data,
  Variables extends AnyVariables,
> = (config: {
  data: Data;
  variables: Variables;
  prepend: AddEdges;
  append: AddEdges;
  remove: RemoveEdges;
}) => ConnectionUpdate<unknown> | undefined;

/** Options of `useMutation` and `Client#mutate`. */
export type MutationConfig<Data, Variables extends AnyVariables> = {
  /** Changes to apply to cached connections when the mutation succeeds. */
  connectionUpdates?: GetConnectionUpdate<Data, Variables>[] | undefined;
};

/**
 * Sends GraphQL requests and keeps the responses in a normalized cache.
 * Give it to `ClientProvider` to use the hooks.
 *
 * @see https://zoontek.github.io/gql-client/client
 */
export class Client {
  /** @internal */
  public cache: ClientCache;

  private url: string;
  private timeout: number;
  private transformRequest: (request: Request) => Request | Promise<Request>;

  private activeQueries = new Set<ActiveQuery>();
  private requests = new WeakMap<object, Map<string, StoredRequest>>();
  private subscribers = new Map<() => void, WatchedEntriesBox>();
  private version = 0;
  // Incremented by `purge` and `restore`. The response of a request sent before
  // is not written to the cache.
  private generation = 0;

  public constructor(config: ClientConfig) {
    this.url = config.url;
    this.cache = new ClientCache(config.schemaConfig);
    this.timeout = config.timeout ?? 10_000;
    this.transformRequest = config.transformRequest ?? identity;
  }

  /** @internal */
  public registerQuery<Data, Variables extends AnyVariables>(
    document: TypedDocumentNode<Data, Variables>,
    variables: NoInfer<Variables>,
  ): () => void {
    const activeQuery: ActiveQuery = { document, variables };
    this.activeQueries.add(activeQuery);

    const release = this.cache.retainQuery(
      transformDocument(document),
      variables,
    );

    return () => {
      release();
      this.activeQueries.delete(activeQuery);
    };
  }

  /**
   * Sends every mounted query again and writes the responses into the cache.
   * Resolves when all requests have settled. Never rejects.
   *
   * @see https://zoontek.github.io/gql-client/refetching
   */
  public async refetch(): Promise<void> {
    await Promise.allSettled(
      [...this.activeQueries].map(({ document, variables }) =>
        this.query(document, variables, { refresh: true }),
      ),
    );
  }

  /** @internal */
  public getVersion(): number {
    return this.version;
  }

  /**
   * Serializes the cache to JSON text, for server-side rendering.
   * Every `<` is escaped, so the text is safe in a `<script>` tag.
   *
   * @see https://zoontek.github.io/gql-client/server-side-rendering
   */
  public extract(): string {
    return JSON.stringify(this.cache.extract()).replace(/</g, "\\u003c");
  }

  /**
   * Replaces the cache content with the output of `extract()`, as a string or
   * as the parsed object, then notifies subscribers. Call it before rendering,
   * on a client that has not fetched anything yet.
   *
   * @see https://zoontek.github.io/gql-client/server-side-rendering
   */
  public restore(data: SerializedCache | string): void {
    this.cache.restore(
      typeof data === "string" ? (JSON.parse(data) as SerializedCache) : data,
    );
    this.reset();
  }

  /**
   * Removes every cache entry, then notifies subscribers so mounted queries
   * fetch again. Responses of requests in flight are not written to the cache.
   * Useful on logout.
   */
  public purge(): void {
    this.cache.purge();
    this.reset();
  }

  private reset(): void {
    this.requests = new WeakMap();
    this.generation++;
    this.version++;
    this.subscribers.forEach((_watched, fn) => {
      fn();
    });
  }

  /**
   * Calls `fn` after each cache write, `restore` and `purge`.
   * Returns a function that removes the subscription.
   */
  public subscribe(
    fn: () => void,
    watched: WatchedEntriesBox = { current: undefined },
  ): () => void {
    this.subscribers.set(fn, watched);
    return () => {
      this.subscribers.delete(fn);
    };
  }

  private notify(touched: Map<object, Set<symbol>>): void {
    this.version++;
    this.subscribers.forEach((watched, fn) => {
      if (entriesOverlap(watched.current, touched)) {
        fn();
      }
    });
  }

  private async request<Data, Variables extends AnyVariables>(
    document: TypedDocumentNode<Data, Variables>,
    variables: NoInfer<Variables>,
    { connectionUpdates }: MutationConfig<Data, Variables> = {},
  ): Promise<Data> {
    const { generation, timeout, transformRequest, url } = this;

    let transformedDocument: TypedDocumentNode;
    let request: Request;

    try {
      // Throws on a missing fragment, a BigInt in the variables, or an invalid
      // URL.
      transformedDocument = transformDocument(document);

      request = new Request(url, {
        cache: "no-store",
        method: "POST",
        headers: {
          Accept: "application/json",
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          operationName: getOperationName(transformedDocument),
          query: printDocument(transformedDocument),
          variables,
        }),
      });
    } catch (error) {
      throw ClientError.unknown(url, error);
    }

    // A promise chain, so a sync throw in `transformRequest` also becomes a
    // ClientError.
    const requestToSend = await Promise.resolve(request)
      .then(transformRequest)
      .catch((error: unknown) => {
        throw ClientError.unknown(url, error);
      });

    if (requestToSend.bodyUsed) {
      throw ClientError.unknown(
        url,
        new TypeError(
          "`transformRequest` returned a consumed request. Read its body from `request.clone()`.",
        ),
      );
    }

    const controller = new AbortController();
    let timedOut = false;

    const timer =
      Number.isFinite(timeout) && timeout >= 0
        ? setTimeout(() => {
            timedOut = true;
            controller.abort();
          }, timeout)
        : undefined;

    // `fetch` listens only to the signal below, so an abort of the request
    // signal (set by `transformRequest`) is forwarded. A polyfilled `Request`
    // can have no signal.
    const requestSignal = requestToSend.signal as AbortSignal | undefined;

    const forwardAbort = (): void => controller.abort();

    if (requestSignal?.aborted === true) {
      controller.abort();
    } else {
      requestSignal?.addEventListener("abort", forwardAbort);
    }

    // The rejection does not always show an abort, because some `fetch`
    // implementations reject with a plain `AbortError`. So the controller
    // signal is checked.
    const getAbortError = (cause: unknown): ClientError | undefined => {
      if (!controller.signal.aborted) {
        return undefined;
      }

      return timedOut
        ? ClientError.timeout(url, timeout, cause)
        : ClientError.aborted(url, cause);
    };

    try {
      let response: Response;

      try {
        response = await fetch(requestToSend, { signal: controller.signal });
      } catch (error) {
        throw getAbortError(error) ?? ClientError.network(url, error);
      }

      if (!response.ok) {
        // Some servers send GraphQL errors with a 4xx status. A clone is read,
        // so `error.response` stays readable.
        const body: unknown = await response
          .clone()
          .json()
          .catch(() => undefined);

        const errors = isRecord(body) ? getGraphQLErrors(body) : undefined;

        throw errors != null
          ? ClientError.graphQL(url, response, errors)
          : ClientError.status(response);
      }

      let json: JsonValue;

      try {
        json = await response.json();
      } catch (error) {
        throw (
          getAbortError(error) ??
          (error instanceof SyntaxError
            ? ClientError.malformed(url, response, error)
            : ClientError.network(url, error))
        );
      }

      if (!isRecord(json)) {
        throw ClientError.malformed(url, response);
      }

      // Partial `data` is not written. The failed fields are `null` in it and
      // would replace good cached values.
      const errors = getGraphQLErrors(json);

      if (errors != null) {
        throw ClientError.graphQL(url, response, errors);
      }

      if (json.data == null) {
        throw ClientError.malformed(url, response);
      }

      const data = json.data as Data;

      if (generation === this.generation) {
        const touched = new Map<object, Set<symbol>>();

        try {
          this.cache.writeOperation(
            transformedDocument,
            json.data,
            variables,
            touched,
          );

          connectionUpdates?.forEach((getUpdate) => {
            const result = getUpdate({
              data,
              variables,
              prepend,
              append,
              remove,
            });

            if (result != null) {
              const [connection, update] = result;
              this.cache.updateConnection(connection, update, touched);
            }
          });
        } finally {
          // Notifies about what was written, even if a later step threw.
          this.notify(touched);
        }
      }

      return data;
    } catch (error) {
      throw error instanceof ClientError
        ? error
        : ClientError.unknown(url, error);
    } finally {
      requestSignal?.removeEventListener("abort", forwardAbort);
      clearTimeout(timer);
    }
  }

  /**
   * Sends a mutation, writes the response into the cache, and resolves with the
   * response data. Each call sends a new request.
   * Rejects with a `ClientError` on failure.
   *
   * @see https://zoontek.github.io/gql-client/mutations
   */
  public mutate<Data, Variables extends AnyVariables>(
    document: TypedDocumentNode<Data, Variables>,
    variables: NoInfer<Variables>,
    config: MutationConfig<Data, Variables> = {},
  ): Promise<Data> {
    return this.request(document, variables, config);
  }

  /**
   * Sends a query, writes the response into the cache, and resolves with the
   * response data. A call with the same document and variables as a request in
   * flight reuses that request. With `refresh: true`, a call sends a new
   * request when no request is in flight.
   * Rejects with a `ClientError` on failure.
   */
  public query<Data, Variables extends AnyVariables>(
    document: TypedDocumentNode<Data, Variables>,
    variables: NoInfer<Variables>,
    {
      refresh = false,
      suspense = false,
    }: { refresh?: boolean; suspense?: boolean } = {},
  ): Promise<Data> {
    const key = serializeVariables(variables);
    const requests = getOrInsert(
      this.requests,
      document,
      () => new Map<string, StoredRequest>(),
    );
    const existing = requests.get(key);

    const expired =
      existing?.rejectedAt != null &&
      Date.now() - existing.rejectedAt > KEEP_REJECTED_MS;

    if (existing != null && !expired && (!existing.settled || !refresh)) {
      if (existing.rejectedAt != null) {
        // Removed soon after this call, so a render that React repeats at once
        // (Strict Mode, error recovery) gets the same promise.
        queueMicrotask(() => {
          deleteIfUnchanged(requests, key, existing);
        });
      } else if (suspense) {
        existing.suspense = true;
      }

      return existing.promise as Promise<Data>;
    }

    const promise = this.request(document, variables);
    const stored: StoredRequest = {
      promise,
      settled: false,
      rejectedAt: undefined,
      suspense,
    };

    requests.set(key, stored);

    // Both callbacks also mark the promise as handled, so a promise that nobody
    // passes to `use()` never causes an unhandled rejection.
    promise.then(
      () => {
        stored.settled = true;

        // Only a read that still misses needs the settled promise. Removing the
        // others stops their data from piling up until `purge`.
        if (
          requests.get(key) === stored &&
          this.cache.readOperation(document, variables) != null
        ) {
          requests.delete(key);
        }
      },
      () => {
        stored.settled = true;
        stored.rejectedAt = Date.now();

        // A failed request is removed, so a retry sends a new one. A suspended
        // component never committed, so React renders it again from zero and
        // must get this promise back. Else it sends a new request and suspends
        // again, in a loop.
        if (!stored.suspense) {
          deleteIfUnchanged(requests, key, stored);
        }
      },
    );

    return promise;
  }
}
